/**
 * 시작일~종료일 사이의 모든 날짜 반환 (YYYYMMDD 형식)
 * @param string $startDate YYYYMMDD
 * @param string $endDate YYYYMMDD
 * @return array 날짜 배열
 */
function getDatesInRange($startDate, $endDate) {
    $dates = [];
    $current = strtotime(substr($startDate, 0, 4) . '-' . substr($startDate, 4, 2) . '-' . substr($startDate, 6, 2));
    $end = strtotime(substr($endDate, 0, 4) . '-' . substr($endDate, 4, 2) . '-' . substr($endDate, 6, 2));
    while ($current <= $end) {
        $dates[] = date('Ymd', $current);
        $current = strtotime('+1 day', $current);
    }
    return $dates;
}

/**
 * API 호출 후 XML에서 entpId(점포ID) 목록 추출
 * @param int $goodId 상품ID
 * @return array entpId 값 배열
 */
function getEntpIdsFromApi($apiBaseUrl, $apiServiceKey, $goodInspectDay, $goodId) {
    $url = $apiBaseUrl . '?' . http_build_query([
        'serviceKey' => $apiServiceKey,
        'goodInspectDay' => $goodInspectDay,
        'goodId' => $goodId
    ]);
    $response = @file_get_contents($url);
    if ($response === false) {
        return [];
    }
    $xml = @simplexml_load_string($response);
    if ($xml === false) {
        return [];
    }
    $entpIds = [];
    $items = $xml->xpath('//*[local-name()="entpId"]');
    foreach ($items as $node) {
        $val = trim((string)$node);
        if ($val !== '') {
            $entpIds[$val] = true;
        }
    }
    return array_keys($entpIds);
}

